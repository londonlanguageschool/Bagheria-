// 14 Oct 2026: the homework each v3 deck shows on its exit slide ("Homework · Compiti"),
// so the portal can suggest exactly what the class saw on the slides.
// Run: node tools/make-deck-homework.js  (reads ../lls-course/v2/lessons, writes deck-homework.js)
const fs = require("fs"), path = require("path");
const SRC = process.env.LESSONS || "/home/claude/lls-course/v2/lessons";
const BOOK = { B1: "EF-B1", A2: "EF-A2B1", B2: "EF-B2", EFE: "EF-A1A2", B1Y: "LLS-B1Y", PREP: "PREP" };
const out = {};
for (const f of fs.readdirSync(SRC).filter((x) => x.endsWith(".js")).sort()) {
  let L;
  try { L = require(path.join(SRC, f)); } catch (e) { console.warn("skip", f, e.message); continue; }
  const book = BOOK[L.prefix || "B1"];
  const s = (L.slides || []).find((x) => Array.isArray(x.hw) && x.hw.length);
  if (!book || !L.id || !s) continue;
  (out[book] = out[book] || {})[L.id] = s.hw.map((t) => String(t).replace(/\*\*/g, "").trim()).filter(Boolean);
}
const js = "/* Generated by tools/make-deck-homework.js — the homework on each deck's last slides. Do not edit by hand. */\n" +
  "window.LLS_DECK_HW = " + JSON.stringify(out, null, 1) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "deck-homework.js"), js);
console.log(Object.entries(out).map(([k, v]) => k + ": " + Object.keys(v).length).join(", "));
